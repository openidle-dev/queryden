import { useEffect, useMemo, useRef, useState } from "react";
import { CheckCircle, Code2, Copy, XCircle } from "lucide-react";
import "../editor/monacoSetup";
import Editor from "@monaco-editor/react";
import { defineMonacoThemes, resolveMonacoTheme } from "../../utils/monacoThemes";
import { useTheme } from "../../contexts/ThemeContext";
import { useSettings } from "../../store/settingsStore";
import { GENERATE_SQL_KINDS, generateSql, missingKeyColumns, type GenerateSqlKind, type GenerateSqlOptions, type GenerateSqlTarget } from "../../utils/sqlGenerate";
import { Dialog } from "../ui/Dialog";
import { Button } from "../ui/Button";
import { cn } from "../../lib/cn";

export type GeneratedSqlKind = GenerateSqlKind | "ddl";

/** Monaco slows to a crawl on multi-MB text (e.g. INSERTs carrying files); Copy still gets everything. */
const MAX_PREVIEW_CHARS = 1_000_000;

interface GenerateSqlDialogProps {
  open: boolean;
  initialKind: GeneratedSqlKind;
  /** Shown in the title, e.g. the connection name. */
  source?: string;
  target: GenerateSqlTarget;
  rows: Record<string, unknown>[];
  /** CREATE statement for the table; omit to hide the DDL option. */
  loadDdl?: () => Promise<string>;
  onClose: () => void;
}

const KIND_TABS: { kind: GeneratedSqlKind; label: string }[] = [...GENERATE_SQL_KINDS, { kind: "ddl", label: "DDL" }];

export function GenerateSqlDialog({ open, initialKind, source, target, rows, loadDdl, onClose }: GenerateSqlDialogProps) {
  const { theme } = useTheme();
  const options = useSettings((s) => s.generateSqlOptions);
  const setSetting = useSettings((s) => s.setSetting);
  const [kind, setKind] = useState<GeneratedSqlKind>(initialKind);
  const [ddl, setDdl] = useState<{ text: string; loading: boolean } | null>(null);
  const [copyStatus, setCopyStatus] = useState<"copied" | "failed" | null>(null);

  useEffect(() => {
    if (open) setKind(initialKind);
  }, [open, initialKind]);

  // The parent's loader is a new function on every render; reading it through
  // a ref keeps a re-render from cancelling the fetch in flight.
  const loadDdlRef = useRef(loadDdl);
  loadDdlRef.current = loadDdl;
  const canLoadDdl = !!loadDdl;

  // Fetched once per open, the first time the DDL tab is shown.
  useEffect(() => {
    if (!open) {
      setDdl(null);
      return;
    }
    const load = loadDdlRef.current;
    if (kind !== "ddl" || ddl || !load) return;
    let cancelled = false;
    setDdl({ text: "", loading: true });
    load()
      .then((text) => { if (!cancelled) setDdl({ text, loading: false }); })
      .catch((e) => { if (!cancelled) setDdl({ text: `-- Could not load the table definition: ${e instanceof Error ? e.message : String(e)}`, loading: false }); });
    return () => { cancelled = true; };
    // `ddl` is excluded: setting it to "loading" must not cancel this fetch.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, kind, canLoadDdl]);

  const missingKeys = useMemo(() => missingKeyColumns(target), [target]);
  const sql = useMemo(() => {
    if (kind === "ddl") return ddl?.text ?? "";
    return generateSql(kind, target, rows, options);
  }, [kind, ddl, target, rows, options]);

  const preview = sql.length > MAX_PREVIEW_CHARS
    ? `${sql.slice(0, MAX_PREVIEW_CHARS)}\n\n-- … preview cut at ${MAX_PREVIEW_CHARS.toLocaleString()} of ${sql.length.toLocaleString()} characters. Copy includes everything.`
    : sql;

  const setOption = (key: keyof GenerateSqlOptions, value: boolean) =>
    setSetting("generateSqlOptions", { ...options, [key]: value });

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(sql);
      setCopyStatus("copied");
    } catch {
      setCopyStatus("failed");
    }
    setTimeout(() => setCopyStatus(null), 2000);
  };

  const tabs = canLoadDdl ? KIND_TABS : KIND_TABS.filter((t) => t.kind !== "ddl");
  const settingsDisabled = kind === "ddl";
  const autoGeneratedKnown = target.autoGeneratedColumns.length > 0;

  return (
    // Modal like DBeaver's: closes with Close, ✕ or Esc, never from a stray
    // click on the backdrop while scrolling or selecting in the preview.
    <Dialog open={open} onClose={onClose} className="max-w-5xl h-[75vh]" dismissOnBackdrop={false}>
      <Dialog.Title onClose={onClose}>
        <span className="flex items-center gap-2">
          <Code2 className="w-4 h-4 text-[var(--accent-11)]" />
          Generated SQL{source ? ` (${source})` : ""}
        </span>
      </Dialog.Title>

      <div className="flex items-center gap-1 px-3 py-2 border-b border-[var(--neutral-6)] overflow-x-auto shrink-0" role="tablist">
        {tabs.map((t) => (
          <button
            key={t.kind}
            type="button"
            role="tab"
            aria-selected={kind === t.kind}
            onClick={() => setKind(t.kind)}
            className={cn(
              "px-2.5 py-1 rounded-md text-[11px] font-medium whitespace-nowrap transition-colors cursor-pointer",
              kind === t.kind
                ? "bg-[var(--accent-9)] text-white"
                : "text-[var(--neutral-11)] hover:text-[var(--neutral-12)] hover:bg-[var(--neutral-4)]",
            )}
          >
            {t.label}
          </button>
        ))}
        <span className="ml-auto pl-3 text-[10px] text-[var(--neutral-11)] whitespace-nowrap">
          {kind === "select" || kind === "ddl" ? target.table : `${rows.length} row${rows.length === 1 ? "" : "s"} · ${target.table}`}
        </span>
      </div>

      <div className="flex-1 min-h-0 relative">
        {kind === "ddl" && ddl?.loading ? (
          <div className="absolute inset-0 flex items-center justify-center text-xs text-[var(--neutral-11)]">Loading table definition…</div>
        ) : (
          <Editor
            height="100%"
            language="sql"
            theme={resolveMonacoTheme(theme)}
            beforeMount={defineMonacoThemes}
            value={preview}
            options={{
              readOnly: true,
              minimap: { enabled: false },
              fontSize: 13,
              fontFamily: "'JetBrains Mono', monospace",
              lineNumbers: "on",
              wordWrap: "on",
              scrollBeyondLastLine: false,
              automaticLayout: true,
              padding: { top: 12 },
            }}
          />
        )}
      </div>

      <fieldset className="px-4 py-2 border-t border-[var(--neutral-6)] shrink-0" disabled={settingsDisabled}>
        <legend className="sr-only">Settings</legend>
        <div className={cn("flex flex-wrap items-center gap-x-5 gap-y-1 text-xs", settingsDisabled && "opacity-50")}>
          <span className="text-[10px] uppercase font-bold tracking-widest text-[var(--neutral-11)]">Settings</span>
          <label className="flex items-center gap-1.5 cursor-pointer">
            <input type="checkbox" className="accent-[var(--accent-9)]" checked={options.qualifiedNames} onChange={(e) => setOption("qualifiedNames", e.target.checked)} />
            Use fully qualified names
          </label>
          <label className="flex items-center gap-1.5 cursor-pointer">
            <input type="checkbox" className="accent-[var(--accent-9)]" checked={options.compact} onChange={(e) => setOption("compact", e.target.checked)} />
            Compact SQL
          </label>
          <label
            className="flex items-center gap-1.5 cursor-pointer"
            title={autoGeneratedKnown ? `Leaves out ${target.autoGeneratedColumns.join(", ")}` : "No identity, serial, auto-increment or generated columns found on this table"}
          >
            <input type="checkbox" className="accent-[var(--accent-9)]" checked={options.excludeAutoGenerated} onChange={(e) => setOption("excludeAutoGenerated", e.target.checked)} />
            Exclude auto-generated columns
          </label>
        </div>
      </fieldset>

      <Dialog.Footer>
        {missingKeys.length > 0 && (kind === "selectByKey" || kind === "update" || kind === "deleteByKey" || kind === "upsert") && (
          <span className="mr-auto text-[10px] text-[var(--warning-11)]">Add {missingKeys.join(", ")} to the query to generate key-matched statements.</span>
        )}
        {target.keyColumns.length === 0 && kind !== "select" && kind !== "insert" && kind !== "ddl" && (
          <span className="mr-auto text-[10px] text-[var(--warning-11)]">No primary key known: rows are matched on every column.</span>
        )}
        <Button size="sm" variant="primary" onClick={() => void handleCopy()} leftIcon={<Copy className="w-3.5 h-3.5" />} disabled={!sql}>
          Copy
        </Button>
        <Button size="sm" variant="secondary" onClick={onClose}>Close</Button>
      </Dialog.Footer>

      {copyStatus && (
        <div className={cn(
          "fixed bottom-10 right-10 text-white px-4 py-2 rounded-md shadow-xl text-xs font-bold flex items-center gap-2 z-[300]",
          copyStatus === "copied" ? "bg-[var(--success-9)]" : "bg-[var(--danger-9)]",
        )}>
          {copyStatus === "copied" ? <><CheckCircle className="w-4 h-4" /> Copied</> : <><XCircle className="w-4 h-4" /> Failed to copy</>}
        </div>
      )}
    </Dialog>
  );
}
