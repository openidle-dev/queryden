import { describe, expect, it } from "vitest";
import { generateSql, quoteName, tableReference, type GenerateSqlOptions, type GenerateSqlTarget } from "./sqlGenerate";

const target: GenerateSqlTarget = {
  table: "res_partner",
  schema: "public",
  columns: ["id", "name", "ref", "note"],
  keyColumns: ["id"],
  autoGeneratedColumns: ["id"],
  dialect: "postgres",
};
const row = { id: 33, name: "O'Brien", ref: "R1", note: null };
const opts: GenerateSqlOptions = { qualifiedNames: true, compact: false, excludeAutoGenerated: false };

describe("quoteName", () => {
  it("quotes reserved words, mixed case and odd characters only", () => {
    expect(quoteName("name", "postgres")).toBe("name");
    expect(quoteName("user", "postgres")).toBe('"user"');
    expect(quoteName("order", "mysql")).toBe("`order`");
    expect(quoteName("CamelCase", "postgres")).toBe('"CamelCase"');
    expect(quoteName("CamelCase", "mysql")).toBe("CamelCase");
    expect(quoteName('we"ird', "postgres")).toBe('"we""ird"');
  });
});

describe("tableReference", () => {
  it("qualifies with the resolved schema when asked", () => {
    expect(tableReference(target, true)).toBe("public.res_partner");
    expect(tableReference(target, false)).toBe("res_partner");
  });

  it("keeps the schema the query wrote and re-quotes quoted parts", () => {
    expect(tableReference({ ...target, table: 'ansible."Job Log"' }, true)).toBe('ansible."Job Log"');
    expect(tableReference({ ...target, table: 'ansible."Job Log"' }, false)).toBe('"Job Log"');
  });
});

describe("generateSql", () => {
  it("lays out INSERT like DBeaver", () => {
    expect(generateSql("insert", target, [row], opts)).toBe(
      "INSERT INTO public.res_partner\n(id, name, ref, note)\nVALUES(33, 'O''Brien', 'R1', NULL);",
    );
  });

  it("puts each statement on one line when compact", () => {
    expect(generateSql("deleteByKey", target, [row, { ...row, id: 34 }], { ...opts, compact: true })).toBe(
      "DELETE FROM public.res_partner WHERE id=33;\nDELETE FROM public.res_partner WHERE id=34;",
    );
  });

  it("leaves auto-generated columns out of INSERT when asked", () => {
    expect(generateSql("insert", target, [row], { ...opts, excludeAutoGenerated: true, compact: true })).toBe(
      "INSERT INTO public.res_partner (name, ref, note) VALUES('O''Brien', 'R1', NULL);",
    );
  });

  it("updates non-key columns keyed on the primary key", () => {
    expect(generateSql("update", target, [row], { ...opts, compact: true })).toBe(
      "UPDATE public.res_partner SET name='O''Brien', ref='R1', note=NULL WHERE id=33;",
    );
  });

  it("matches on every column, with IS NULL, when there is no key", () => {
    expect(generateSql("selectByKey", { ...target, keyColumns: [] }, [row], { ...opts, compact: true })).toBe(
      "SELECT id, name, ref, note FROM public.res_partner WHERE id=33 AND name='O''Brien' AND ref='R1' AND note IS NULL;",
    );
  });

  it("writes one SELECT for the table regardless of rows", () => {
    expect(generateSql("select", target, [row, row], opts)).toBe("SELECT id, name, ref, note\nFROM public.res_partner;");
  });

  it("upserts with ON CONFLICT on PostgreSQL and ON DUPLICATE KEY on MySQL", () => {
    expect(generateSql("upsert", target, [row], { ...opts, compact: true })).toBe(
      "INSERT INTO public.res_partner (id, name, ref, note) VALUES(33, 'O''Brien', 'R1', NULL) ON CONFLICT (id) DO UPDATE SET name=EXCLUDED.name, ref=EXCLUDED.ref, note=EXCLUDED.note;",
    );
    expect(generateSql("upsert", { ...target, dialect: "mysql", schema: "odoo" }, [row], { ...opts, compact: true })).toBe(
      "INSERT INTO odoo.res_partner (id, name, ref, note) VALUES(33, 'O''Brien', 'R1', NULL) ON DUPLICATE KEY UPDATE name=VALUES(name), ref=VALUES(ref), note=VALUES(note);",
    );
  });

  it("explains instead of guessing a conflict target without a key", () => {
    expect(generateSql("upsert", { ...target, keyColumns: [] }, [row], opts)).toMatch(/^-- MERGE needs the table's primary key/);
  });

  it("refuses key-matched statements when the result omits part of the primary key", () => {
    const partial = { ...target, keyColumns: ["tenant_id", "id"] };
    for (const kind of ["selectByKey", "update", "deleteByKey", "upsert"] as const) {
      expect(generateSql(kind, partial, [row], opts)).toBe(
        "-- Primary key column tenant_id not in the result; a partial key can match many rows in public.res_partner.",
      );
    }
    expect(generateSql("insert", partial, [row], { ...opts, compact: true })).toBe(
      "INSERT INTO public.res_partner (id, name, ref, note) VALUES(33, 'O''Brien', 'R1', NULL);",
    );
  });

  it("separates multi-row output with a blank line", () => {
    expect(generateSql("deleteByKey", target, [row, { ...row, id: 34 }], opts)).toBe(
      "DELETE FROM public.res_partner\nWHERE id=33;\n\nDELETE FROM public.res_partner\nWHERE id=34;",
    );
  });
});
