/**
 * Statement generators behind the results grid's Generate SQL dialog: the
 * DBeaver set (SELECT, SELECT/DELETE by key, INSERT, UPDATE, MERGE) built from
 * result rows. Pure so the quoting and layout rules are unit-tested.
 */

import { formatSqlLiteral, splitDottedIdentifier } from "./sqlDialect";
import type { SqlDialect } from "../components/editor/sqlBuiltins";

export type GenerateSqlKind = "select" | "selectByKey" | "insert" | "update" | "deleteByKey" | "upsert";

export const GENERATE_SQL_KINDS: { kind: GenerateSqlKind; label: string }[] = [
  { kind: "select", label: "SELECT" },
  { kind: "selectByKey", label: "SELECT by Unique Key" },
  { kind: "insert", label: "INSERT" },
  { kind: "update", label: "UPDATE" },
  { kind: "deleteByKey", label: "DELETE by Unique Key" },
  { kind: "upsert", label: "MERGE / UPSERT" },
];

export interface GenerateSqlOptions {
  /** `schema.table` instead of the bare table name. */
  qualifiedNames: boolean;
  /** One line per statement. */
  compact: boolean;
  /** Leave identity / serial / generated columns out of INSERT and MERGE. */
  excludeAutoGenerated: boolean;
}

export interface GenerateSqlTarget {
  /** As the query named it: `t`, `schema.t`, or quoted forms. */
  table: string;
  /** Schema the table resolved to, used when `table` has none. */
  schema?: string;
  columns: string[];
  /** Primary key columns; WHERE falls back to every column when empty. */
  keyColumns: string[];
  autoGeneratedColumns: string[];
  dialect: SqlDialect;
}

type Row = Record<string, unknown>;

/** Words that must be quoted as identifiers in at least one supported engine. */
const RESERVED = new Set([
  "all", "analyse", "analyze", "and", "any", "array", "as", "asc", "asymmetric", "authorization", "between", "binary",
  "both", "by", "case", "cast", "change", "check", "collate", "collation", "column", "concurrently", "condition",
  "constraint", "create", "cross", "current_catalog", "current_date", "current_role", "current_schema", "current_time",
  "current_timestamp", "current_user", "database", "default", "deferrable", "delete", "desc", "describe", "distinct",
  "do", "drop", "else", "end", "except", "exists", "false", "fetch", "for", "foreign", "freeze", "from", "full",
  "grant", "group", "having", "ilike", "in", "index", "initially", "inner", "insert", "intersect", "interval", "into",
  "is", "isnull", "join", "key", "keys", "lateral", "leading", "left", "like", "limit", "localtime", "localtimestamp",
  "match", "natural", "not", "notnull", "null", "offset", "on", "only", "option", "or", "order", "outer", "overlaps",
  "partition", "placing", "primary", "range", "read", "references", "rename", "returning", "right", "row", "rows",
  "select", "session_user", "set", "similar", "some", "symmetric", "system_user", "table", "tablesample", "then", "to",
  "trailing", "trigger", "true", "union", "unique", "update", "usage", "use", "user", "using", "values", "variadic",
  "verbose", "when", "where", "window", "with", "write",
]);

/** An identifier part, quoted when its case, characters or a keyword require it. */
export function quoteName(name: string, dialect: SqlDialect): string {
  const plain = dialect === "mysql" ? /^[A-Za-z_][A-Za-z0-9_$]*$/ : /^[a-z_][a-z0-9_$]*$/;
  if (plain.test(name) && !RESERVED.has(name.toLowerCase())) return name;
  return dialect === "mysql" ? `\`${name.replace(/`/g, "``")}\`` : `"${name.replace(/"/g, '""')}"`;
}

function unquote(part: string): string {
  const first = part[0];
  if ((first === '"' || first === "`") && part.endsWith(first) && part.length >= 2) {
    return part.slice(1, -1).split(first + first).join(first);
  }
  return part;
}

/** `schema.table` as written in a query, unquoted; schema is undefined when not given. */
export function splitTableName(name: string): { schema?: string; table: string } {
  const parts = splitDottedIdentifier(name).map(unquote);
  return { table: parts[parts.length - 1], schema: parts.length > 1 ? parts[parts.length - 2] : undefined };
}

/** The table name as the statements write it. */
export function tableReference(target: Pick<GenerateSqlTarget, "table" | "schema" | "dialect">, qualified: boolean): string {
  const parsed = splitTableName(target.table);
  const table = parsed.table;
  const schema = parsed.schema ?? target.schema;
  const names = qualified && schema ? [schema, table] : [table];
  return names.map((n) => quoteName(n, target.dialect)).join(".");
}

const literal = (value: unknown, dialect: SqlDialect) =>
  typeof value === "number" ? String(value) : formatSqlLiteral(value, dialect);

function whereClause(row: Row, keys: string[], dialect: SqlDialect): string {
  return keys
    .map((c) => (row[c] === null || row[c] === undefined
      ? `${quoteName(c, dialect)} IS NULL`
      : `${quoteName(c, dialect)}=${literal(row[c], dialect)}`))
    .join(" AND ");
}

/** Statement clauses joined on new lines, or on spaces when compact. */
function statement(clauses: string[], compact: boolean): string {
  return `${clauses.join(compact ? " " : "\n")};`;
}

export function generateSql(kind: GenerateSqlKind, target: GenerateSqlTarget, rows: Row[], options: GenerateSqlOptions): string {
  const { dialect } = target;
  const table = tableReference(target, options.qualifiedNames);
  const q = (c: string) => quoteName(c, dialect);
  const keys = target.keyColumns.filter((k) => target.columns.includes(k));
  const whereKeys = keys.length > 0 ? keys : target.columns;
  const autoGenerated = new Set(options.excludeAutoGenerated ? target.autoGeneratedColumns : []);
  const insertColumns = target.columns.filter((c) => !autoGenerated.has(c));
  const nonKeyColumns = target.columns.filter((c) => !keys.includes(c) && !autoGenerated.has(c));
  const setColumns = nonKeyColumns.length > 0 ? nonKeyColumns : target.columns;
  const columnList = (cols: string[]) => cols.map(q).join(", ");
  const values = (row: Row, cols: string[]) => cols.map((c) => literal(row[c], dialect)).join(", ");
  const separator = options.compact ? "\n" : "\n\n";

  if (kind === "select") {
    return statement([`SELECT ${columnList(target.columns)}`, `FROM ${table}`], options.compact);
  }

  if (kind === "upsert" && keys.length === 0 && dialect !== "mysql") {
    return `-- MERGE needs the table's primary key, and none is known for ${table}.`;
  }

  const one = (row: Row): string => {
    switch (kind) {
      case "selectByKey":
        return statement([`SELECT ${columnList(target.columns)}`, `FROM ${table}`, `WHERE ${whereClause(row, whereKeys, dialect)}`], options.compact);
      case "insert":
        return statement([`INSERT INTO ${table}`, `(${columnList(insertColumns)})`, `VALUES(${values(row, insertColumns)})`], options.compact);
      case "update":
        return statement([
          `UPDATE ${table}`,
          `SET ${setColumns.map((c) => `${q(c)}=${literal(row[c], dialect)}`).join(", ")}`,
          `WHERE ${whereClause(row, whereKeys, dialect)}`,
        ], options.compact);
      case "deleteByKey":
        return statement([`DELETE FROM ${table}`, `WHERE ${whereClause(row, whereKeys, dialect)}`], options.compact);
      case "upsert": {
        const head = [`INSERT INTO ${table}`, `(${columnList(insertColumns)})`, `VALUES(${values(row, insertColumns)})`];
        const updatable = nonKeyColumns.filter((c) => insertColumns.includes(c));
        if (dialect === "mysql") {
          const assignments = (updatable.length > 0 ? updatable : insertColumns).map((c) => `${q(c)}=VALUES(${q(c)})`).join(", ");
          return statement([...head, `ON DUPLICATE KEY UPDATE ${assignments}`], options.compact);
        }
        const conflict = `ON CONFLICT (${columnList(keys)})`;
        if (updatable.length === 0) return statement([...head, `${conflict} DO NOTHING`], options.compact);
        return statement([...head, `${conflict} DO UPDATE`, `SET ${updatable.map((c) => `${q(c)}=EXCLUDED.${q(c)}`).join(", ")}`], options.compact);
      }
      default:
        return "";
    }
  };

  return rows.map(one).join(separator);
}
